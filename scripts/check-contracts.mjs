// Fails when the committed generated client (src/api/generated/) or messages
// (src/messages/) differ from what the pinned contracts version gives
// (EPIC-11 spec, section 2.9). It regenerates both into a temporary folder,
// compares file by file, and writes nothing in the tree it checks. Offline
// once `npm ci` has run.
import { mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  GENERATED_CLIENT_DIR,
  GENERATED_MESSAGES_DIR,
  REPO_ROOT,
  writeClient,
  writeMessages,
} from "./lib/contracts.mjs";

/** Every file under `dir`, as paths relative to it with `/`, sorted. */
function filesUnder(dir) {
  try {
    return readdirSync(dir, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => join(entry.parentPath, entry.name).slice(dir.length + 1).replaceAll("\\", "/"))
      .sort();
  } catch {
    return [];
  }
}

const text = (file) => readFileSync(file, "utf8").replaceAll("\r\n", "\n");

function compare(label, expectedDir, committedDir) {
  const problems = [];
  const expected = filesUnder(expectedDir);
  const committed = filesUnder(committedDir);
  for (const file of expected) {
    if (!committed.includes(file)) problems.push(`${label}/${file}: missing`);
    else if (text(join(expectedDir, file)) !== text(join(committedDir, file))) {
      problems.push(`${label}/${file}: differs from the pinned contracts version`);
    }
  }
  for (const file of committed) {
    if (!expected.includes(file)) problems.push(`${label}/${file}: not generated by the pinned version`);
  }
  return problems;
}

const temp = mkdtempSync(join(tmpdir(), "tripmate-web-check-contracts-"));
let problems;
try {
  await writeClient(temp);
  writeMessages(join(temp, GENERATED_MESSAGES_DIR));
  problems = [
    ...compare(GENERATED_CLIENT_DIR, join(temp, GENERATED_CLIENT_DIR), join(REPO_ROOT, GENERATED_CLIENT_DIR)),
    ...compare(GENERATED_MESSAGES_DIR, join(temp, GENERATED_MESSAGES_DIR), join(REPO_ROOT, GENERATED_MESSAGES_DIR)),
  ];
} finally {
  rmSync(temp, { recursive: true, force: true });
}

if (problems.length > 0) {
  console.error("check:contracts: the generated files do not match the pinned contracts version:");
  for (const problem of problems) console.error(`  ${problem}`);
  console.error("Run `npm run generate:contracts` and commit the result.");
  process.exit(1);
}
console.log("check:contracts: the generated client and messages match the pinned contracts version.");
